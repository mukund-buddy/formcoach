export let lang = "hinglish";

export async function initLang(storage) {
  try {
    const saved = await storage.kvGet("lang");
    if (saved && D[saved]) lang = saved;
  } catch {
    /* storage fail — default hinglish */
  }
}

export function setLang(l) {
  if (D[l]) lang = l;
}

export function t(key) {
  const d = D[lang] || D.hinglish;
  return d[key] ?? D.hinglish[key] ?? key;
}

export function tpl(key, vars) {
  let s = t(key);
  for (const [k, v] of Object.entries(vars || {})) {
    s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export function voiceLang() {
  return lang === "english" ? "en-IN" : "hi-IN";
}

export function dateLocale() {
  return lang === "english" ? "en-IN" : "hi-IN";
}

export function tutSteps(ex) {
  const d = D[lang] || D.hinglish;
  return d[`tut_${ex}`] || [];
}

export function poseInstructions() {
  const d = D[lang] || D.hinglish;
  return d.pose || D.hinglish.pose;
}
